def normalized_trend_strength(df):
    df = df.sort_values("Date")
    t = np.arange(len(df)).reshape(-1, 1)
    y = df["Volume"].values
    if len(y) < 5 or np.isnan(y).all():
        return np.nan
    model = LinearRegression()
    model.fit(t, y)
    slope = model.coef_[0]
    mean_vol = np.mean(y)
    return np.abs(slope) / mean_vol if mean_vol != 0 else np.nan

